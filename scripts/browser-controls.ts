import assert from 'node:assert/strict';
import { chromium, webkit } from 'playwright';
import { serveBuild } from './browser-server';

const engines = { chromium, webkit };
const app = await serveBuild(process.env.TEST_BUILD_DIR);
try {
  for (const engine of process.argv.slice(2).length ? process.argv.slice(2) : Object.keys(engines)) {
    const type = engines[engine as keyof typeof engines];
    assert(type, `Unknown browser: ${engine}`);
    const browser = await type.launch();
    try {
      for (const viewport of [{ width: 320, height: 568 }, { width: 568, height: 320 }]) {
        const context = await browser.newContext({ viewport, hasTouch: true, serviceWorkers: 'block', locale: 'en-US' });
        const page = await context.newPage();
        const errors: Error[] = [];
        page.on('pageerror', error => errors.push(error));
        const button = (name: string | RegExp) => page.getByRole('button', { name, exact: typeof name === 'string' });
        await page.goto(app.url);
        await button('Weekly Challenge').waitFor({ timeout: 4000 });
        await button('Endless Mode').press('Enter');
        const board = button(/^Battlefield, column/);
        await board.waitFor();
        const launch = button(/^Start wave/);
        const auto = button('Skip wave interval');
        await auto.waitFor({ timeout: 3000 });
        await auto.press('Enter');
        await page.waitForFunction(() => document.querySelector('button[aria-label="Skip wave interval"]')?.getAttribute('aria-pressed') === 'true');
        await auto.press('Enter');
        assert(await launch.boundingBox());
        const status = page.locator('#battle-status');
        assert.match((await status.textContent()) ?? '', /Gold.*Lives.*Wave.*Score/i);
        await button('Operations briefing').press('Enter');
        const ops = page.getByRole('dialog', { name: 'Operations briefing' });
        await ops.getByRole('heading', { name: /next wave/i }).waitFor();
        await ops.getByRole('heading', { name: /daily objectives/i }).waitFor();
        assert.equal(await ops.locator('#ops-title').evaluate(title => getComputedStyle(title).outlineStyle), 'none');
        const [dialogBox, closeBox] = await Promise.all([ops.boundingBox(), ops.getByRole('button', { name: 'Close' }).boundingBox()]);
        assert(dialogBox && closeBox && closeBox.y + closeBox.height <= dialogBox.y + dialogBox.height,
          'briefing close action must be visible without scrolling');
        const details = ops.getByRole('region', { name: 'Briefing details' });
        const heading = ops.getByRole('heading', { name: 'Achievements' });
        await heading.scrollIntoViewIfNeeded();
        const [scrollerBox, achievementBox] = await Promise.all([details.boundingBox(), heading.boundingBox()]);
        assert(scrollerBox && achievementBox && achievementBox.y >= scrollerBox.y
          && achievementBox.y + achievementBox.height <= scrollerBox.y + scrollerBox.height,
          'achievements remain reachable in the scrollable briefing');
        await details.getByText('View all achievements', { exact: true }).click();
        assert.equal(await details.locator('details').getAttribute('open'), '');
        assert((await details.locator('details li').count()) > 0);
        await ops.getByRole('button', { name: 'Close' }).click();
        await ops.waitFor({ state: 'hidden' });
        await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Operations briefing');
        if (viewport.height < 400) {
          for (let i = 0; i < 9; i++) await board.press('ArrowDown');
          await board.press('ArrowRight');
          await button(/battlefield.*column 3.*row 11.*open building site/i).waitFor();
          const tile = await board.boundingBox();
          assert(tile);
          await page.touchscreen.tap(tile.x + tile.width / 2, tile.y + tile.height / 2);
          await page.waitForFunction(() => (document.querySelector('#battle-status')?.textContent ?? '').includes('Tap again'));
          assert.match((await board.getAttribute('aria-label')) ?? '', /open building site/i);
          await page.touchscreen.tap(tile.x + tile.width / 2, tile.y + tile.height / 2);
          await button(/battlefield.*column 3.*row 11.*turret/i).waitFor();
          await page.setViewportSize({ width: 320, height: 568 });
          await page.waitForFunction(() => document.querySelector('button[aria-label="Skip wave interval"]')?.getBoundingClientRect().y === 33);
          await button(/battlefield.*column 3.*row 11.*turret/i).waitFor();
          await button('Pause').press('Enter');
          await button('Settings').press('Enter');
          const settingsPanel = page.getByRole('dialog', { name: 'Settings' });
          const preview = settingsPanel.getByRole('button', { name: 'Preview shake' });
          const miniMap = settingsPanel.locator('canvas');
          const shake = settingsPanel.getByRole('slider', { name: 'Screen shake' });
          await shake.press('End');
          await shake.press('ArrowLeft');
          assert.equal(await shake.inputValue(), '149');
          await preview.tap();
          await page.waitForFunction(() => !!document.querySelector<HTMLCanvasElement>('#settings-screen canvas')?.style.transform);
          await page.waitForFunction(() => !document.querySelector<HTMLCanvasElement>('#settings-screen canvas')?.style.transform);
          const motion = button('Reduce motion');
          await motion.press('Enter');
          assert.equal(await motion.getAttribute('aria-pressed'), 'true');
          assert.equal(await preview.isDisabled(), true);
          assert.equal(await shake.inputValue(), '149');
          assert.equal(await miniMap.evaluate((map: HTMLCanvasElement) => map.style.transform), '');
          await settingsPanel.getByRole('combobox', { name: 'Language' }).selectOption('zh');
          await page.getByRole('combobox', { name: '语言' }).waitFor();
          await page.reload();
          await button('继续').press('Enter');
          await page.getByRole('button', { name: /^战场/ }).waitFor();
          assert.equal(await page.evaluate(() => document.documentElement.lang), 'zh-Hans');
          await button('暂停').press('Enter');
          await button('设置').press('Enter');
          const localizedShake = page.getByRole('slider', { name: '画面震动' });
          assert.equal(await localizedShake.inputValue(), '149');
          assert.equal(await button('预览震动').isDisabled(), true);
          await button('减少动效').press('Enter');
          assert.equal(await button('预览震动').isEnabled(), true);
          await localizedShake.press('Home');
          assert.equal(await localizedShake.inputValue(), '0');
          assert.equal(await button('预览震动').isDisabled(), true);
        }
        assert.deepEqual(errors, []);
        console.log(`PASS ${engine} ${viewport.width}×${viewport.height}: HUD controls, accessible briefing, focus recovery${viewport.height < 400 ? ', two-tap building' : ''}`);
        await context.close();
      }
      const talents = await browser.newContext({ viewport: { width: 1380, height: 778 }, serviceWorkers: 'block', locale: 'en-US' });
      const talentPage = await talents.newPage();
      const talentButton = (name: string) => talentPage.getByRole('button', { name, exact: true });
      await talentPage.goto(app.url);
      await talentButton('Daily Challenge').press('Enter');
      await talentButton('Pause').press('Enter');
      await talentButton('Talent').press('Enter');
      const talentDialog = talentPage.getByRole('dialog', { name: 'Talents' });
      await talentDialog.waitFor();
      assert.equal(await talentDialog.getByRole('listitem').count(), 6);
      assert.equal(await talentDialog.getByText('Daily and weekly challenges use fixed talents.').count(), 1);
      const unaffordable = talentDialog.getByRole('button', { name: 'Greed · 1 pt short' });
      assert.equal(await unaffordable.isDisabled(), true);
      const unaffordableBox = await unaffordable.boundingBox();
      assert(unaffordableBox);
      await talentPage.mouse.click(unaffordableBox.x + unaffordableBox.width / 2, unaffordableBox.y + unaffordableBox.height / 2);
      assert.equal(await talentDialog.isVisible(), true, 'Tapping a disabled talent must keep the screen open');
      await talentPage.keyboard.press('Escape');
      await talentDialog.waitFor({ state: 'hidden' });
      await talentPage.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Talent');
      await talentButton('Resume').waitFor();
      await talentButton('Intel').press('Enter');
      const intel = talentPage.getByRole('dialog', { name: 'INTEL CODEX' });
      await intel.waitFor();
      assert.equal(await intel.locator('#codex-list > li').count(), 6);
      await intel.getByRole('button', { name: 'Enemies', exact: true }).press('Enter');
      assert.equal(await intel.locator('#codex-list > li canvas').count(), 7);
      await intel.getByRole('heading', { name: 'Titan', exact: true }).waitFor();
      await intel.getByRole('button', { name: 'Back to pause' }).press('Enter');
      await intel.waitFor({ state: 'hidden' });
      await talentPage.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Intel');
      await talents.close();

      const talentPhone = await browser.newContext({
        viewport: { width: 320, height: 568 }, serviceWorkers: 'block', locale: 'en-US', hasTouch: true, isMobile: true,
      });
      const purchases = await talentPhone.newPage();
      const purchaseButton = (name: string) => purchases.getByRole('button', { name, exact: true });
      await purchases.addInitScript(() => localStorage.setItem('praesidium:save', JSON.stringify({ talents: { points: 2, ranks: { damage: 4 } } })));
      await purchases.goto(app.url);
      await purchaseButton('Endless Mode').tap();
      await purchaseButton('Pause').press('Enter');
      await purchaseButton('Talent').press('Enter');
      const purchaseDialog = purchases.getByRole('dialog', { name: 'Talents' });
      await purchaseDialog.waitFor();
      const back = purchaseDialog.getByRole('button', { name: 'Back to pause' });
      const backBox = await back.boundingBox();
      assert(backBox && backBox.height >= 44);
      await purchaseDialog.getByRole('button', { name: 'Arcane · 1 pt short' }).scrollIntoViewIfNeeded();
      assert(await purchaseDialog.locator('.talent-scroll').evaluate(element => element.scrollTop) > 0);
      assert.deepEqual(await back.boundingBox(), backBox);
      await purchaseDialog.getByRole('button', { name: 'Power · Upgrade · 1 pt' }).tap();
      await purchaseDialog.getByRole('status').getByText('Power upgraded to rank 5.').waitFor();
      assert.equal(await purchaseDialog.locator('[data-talent="points"]').textContent(), '1');
      assert.equal(await purchaseDialog.getByRole('button', { name: 'Power · Max rank' }).isDisabled(), true);
      await back.tap();
      await purchaseDialog.waitFor({ state: 'hidden' });
      await purchases.reload();
      await purchaseButton('Resume').press('Enter');
      await purchaseButton('Pause').press('Enter');
      await purchaseButton('Talent').press('Enter');
      await purchaseDialog.getByRole('button', { name: 'Power · Max rank' }).waitFor();
      assert.equal(await purchaseDialog.locator('[data-talent="points"]').textContent(), '1');
      console.log(`PASS ${engine}: native talent page, disabled tap, pause focus, scrollable mobile layout and saved upgrade`);
      await purchaseDialog.getByRole('button', { name: 'Back to pause' }).tap();
      await purchaseButton('Stats').press('Enter');
      await purchaseButton('Rankings').press('Enter');
      const boardFilter = purchaseButton('Choose leaderboard');
      await boardFilter.waitFor();
      assert((await boardFilter.boundingBox())!.height >= 44);
      await boardFilter.press('Enter');
      const filter = purchases.getByRole('dialog', { name: 'Choose leaderboard' });
      await filter.getByLabel('Leaderboard type').selectOption('level');
      await filter.getByLabel(/^level$/i).selectOption({ value: '9' });
      await filter.getByLabel('Difficulty').selectOption('hard');
      await filter.getByRole('button', { name: 'View leaderboard' }).tap();
      await filter.waitFor({ state: 'hidden' });
      const stats = purchases.getByRole('dialog', { name: 'Statistics', exact: true });
      await stats.getByRole('heading', { name: 'Level 10 leaderboard' }).waitFor();
      console.log(`PASS ${engine}: matching unit art in Intel, focus recovery and mobile leaderboard filters`);
      await talentPhone.close();

      const challenge = await browser.newContext({ serviceWorkers: 'block', locale: 'en-US' });
      const page = await challenge.newPage();
      await page.goto(app.url);
      await page.getByRole('button', { name: 'Stats', exact: true }).click();
      const emptyStats = page.getByRole('dialog', { name: 'Statistics', exact: true });
      await emptyStats.getByRole('heading', { name: 'No stats yet' }).waitFor();
      assert.equal(await emptyStats.locator('dl').count(), 0);
      await emptyStats.getByRole('button', { name: 'Back', exact: true }).click();
      const seedButton = page.getByRole('button', { name: 'Challenge Seed', exact: true });
      await seedButton.click();
      const input = page.locator('#challenge-code');
      await input.waitFor();
      const focus = await input.evaluate(field => {
        const style = getComputedStyle(field);
        return { active: document.activeElement === field, outline: style.outlineStyle, background: style.backgroundColor };
      });
      assert.deepEqual(focus, { active: true, outline: 'none', background: 'rgb(40, 60, 83)' });
      const closeSeed = page.locator('#challenge-close');
      await input.press('Tab');
      if (engine === 'webkit' && process.platform === 'darwin' && !await closeSeed.evaluate(button => button === document.activeElement)) {
        await input.press('Alt+Tab');
      }
      const keyboardFocus = await closeSeed.evaluate(button => {
        const style = getComputedStyle(button);
        return { active: document.activeElement === button, outline: style.outlineStyle, marker: style.boxShadow };
      });
      assert.equal(keyboardFocus.active, true);
      assert.equal(keyboardFocus.outline, 'none');
      assert.match(keyboardFocus.marker, /inset/);
      await closeSeed.click();
      await seedButton.press('Enter');
      assert.equal(await input.evaluate(field => getComputedStyle(field).outlineStyle), 'none');
      assert.equal(await page.locator('#challenge-label').evaluate(label => getComputedStyle(label).color), 'rgb(242, 197, 132)');
      const code = 'P2-R1-S1-A1784F01-HV-2025-W26-122340';
      await input.fill(code.replace('-R1-', '-R9-'));
      await input.press('Enter');
      await page.getByText(/unsupported challenge rules version/i).waitFor();
      assert.equal(await input.getAttribute('aria-invalid'), 'true');
      await input.fill(code);
      await input.press('Enter');
      await page.getByRole('button', { name: 'Operations briefing' }).press('Enter');
      await page.getByText(/practice run.*activity rewards do not apply/i).waitFor();
      console.log(`PASS ${engine}: rejects unknown P2 versions and starts a supported code as personal practice`);
      await challenge.close();
    } finally { await browser.close(); }
  }
} finally { await app.close(); }
